import { config } from "dotenv";
import { randomUUID } from "node:crypto";
import assert from "node:assert/strict";
config({ path: ".env.local", quiet: true });
const base = process.env.BASE ?? "http://localhost:3100";
const login = await fetch(`${base}/api/auth/sign-in/email`, { method: "POST", headers: { origin: base, "content-type": "application/json" }, body: JSON.stringify({ email: process.env.ADMIN_EMAIL, password: process.env.ADMIN_PASSWORD }) });
assert.equal(login.status, 200);
const cookie = login.headers.getSetCookie().map(c => c.split(";")[0]).join("; ");
const id = randomUUID();
async function send(parts) {
  const response = await fetch(`${base}/api/chat`, { method: "POST", headers: { cookie, origin: base, "content-type": "application/json" }, body: JSON.stringify({ id, message: { id: randomUUID(), role: "user", parts }, selectedChatModel: process.env.OPENAI_COMPATIBLE_MODEL, selectedVisibilityType: "private" }), signal: AbortSignal.timeout(150000) });
  assert.equal(response.status, 200);
  return (await response.text()).split("\n").filter(line => line.startsWith("data: {")).map(line => JSON.parse(line.slice(6)));
}
const events = await send([{ type: "text", text: "Object width = 100 mm Sensor width = 8.8 mm (typical 2/3 inch sensor) Focal length = 25 mm working distance give me a suitable lens model" }]);
const form = events.find(e => e.type === "tool-output-available" && e.output?.prefill && !e.output?.error);
console.log("initial tools", events.filter(e => e.type === "tool-input-available").map(e => e.toolName));
if (!form) console.log("initial result", events.filter(e => e.type === "text-delta").map(e => e.delta).join(""));
assert(form, "working-distance approval form produced");
assert.equal(form.output.formula_id, "working_distance_using_sensor_size");
assert.deepEqual(form.output.prefill, { object_size_mm: 100, sensor_size_mm: 8.8, focal_length_mm: 25 });
assert(!events.some(e => e.toolName === "calculate"), "no calculation before approval");
const pendingDebug = await (await fetch(`${base}/api/admin/conversations/${id}`, { headers: { cookie } })).json();
assert.equal(pendingDebug.workflow.status, "waiting-approval", "plan persisted before the approval pause");
assert(pendingDebug.workflow.steps.some(step => step.area === "catalog"));
assert.deepEqual(pendingDebug.workflow.facts.proposedCalculation.inputs, form.output.prefill);
const approved = await send([{ type: "data-calculationDecision", data: { proposalId: form.toolCallId, action: "approve", args: form.output.prefill } }]);
const calls = approved.filter(e => e.type === "tool-input-available").map(e => e.toolName);
console.log("approved tools", calls);
const sources = approved.filter(e => e.type === "data-sources").at(-1)?.data ?? [];
const catalog = sources.filter(s => s.kind === "catalog");
const answer = approved.filter(e => e.type === "text-delta").map(e => e.delta).join("");
console.log("answer", answer);
assert(calls.includes("calculate") && calls.includes("search_products"));
assert(catalog.length, "real matching catalog models returned");
assert(catalog.every(source => /(?:focus|focal) length mm: 25(?:\n|$)/.test(source.text)), "every candidate preserves the stated 25 mm focal length");
assert(/\[S\d+\]/.test(answer));
assert(!/couldn't finish|try again/i.test(answer));
assert(!approved.some(e => e.type.startsWith("reasoning")));
assert.equal(new Set(sources.map(s => s.id)).size, sources.length);
const debug = await (await fetch(`${base}/api/admin/conversations/${id}`, { headers: { cookie } })).json();
assert.equal(debug.workflow.status, "complete", "durable plan completed after resumed lookup");
assert.equal(debug.workflow.facts.approvedCalculation.output.working_distance_mm, 309.1);
assert(debug.workflow.trace.some(entry => entry.tool === "search_products" && entry.ok));
console.log("PASS exact customer request: approval, working-distance calculation, live lens models, source citations");
